#!/usr/bin/env bun
// Generates contents-{eng,rus}.tex from contents-{eng,rus}.md.
// Usage: bun scripts/md2tex.ts [--check]
//
// MD convention:
//   # Section              -> \cvsection{Section}
//   ## Title | Loc | Dates -> \cventry[oneline]{Title}{Loc}{Dates} (\begin{cvgroup} on first subentry)
//   ### Role | Dates       -> \cvsubentry{Role}{}{Dates}
//   - bullet               -> itemize (consecutive bullets grouped)
//   plain paragraph        -> justify block
//   **bold** inline        -> \textbf{bold}; lines starting with ** stay outside justify
// LaTeX specials (& % $ # _ { }) are escaped; unicode (– →) passes through (LuaLaTeX).

export {};

const LANGS = ["eng", "rus"];

function escapeTex(s: string): string {
  return s.replace(/[&%$#_{}]/g, (c) => "\\" + c);
}

function inline(s: string): string {
  return escapeTex(s).replace(/\*\*([^*]+)\*\*/g, "\\textbf{$1}");
}

function fields(s: string): string[] {
  return s.split("|").map((f) => inline(f.trim()));
}

function pad3(a: string[]): string[] {
  return [a[0] ?? "", a[1] ?? "", a[2] ?? ""];
}

function generate(md: string): string {
  const out: string[] = [];
  let inItemize = false;
  let inCvgroup = false;
  let inJustify = false;
  let lastPlain = false;

  const closeItemize = () => {
    if (inItemize) out.push("\\end{itemize}");
    inItemize = false;
  };
  const closeJustify = () => {
    if (inJustify) out.push("\\end{justify}");
    inJustify = false;
  };
  const closeCvgroup = () => {
    if (inCvgroup) out.push("\\end{cvgroup}");
    inCvgroup = false;
  };

  for (const raw of md.split("\n")) {
    const line = raw.trim();
    if (line === "") {
      closeItemize();
      if (inJustify || lastPlain) out.push("");
      lastPlain = false;
      continue;
    }
    if (line.startsWith("### ")) {
      closeItemize();
      closeJustify();
      if (!inCvgroup) {
        out.push("\\begin{cvgroup}");
        inCvgroup = true;
      }
      const [role, dates] = fields(line.slice(4));
      out.push(`\\cvsubentry{${role}}{}{${dates ?? ""}}`);
    } else if (line.startsWith("## ")) {
      closeItemize();
      closeJustify();
      closeCvgroup();
      const [a, b, c] = pad3(fields(line.slice(3)));
      out.push(`\\cventry[oneline]{${a}}{${b}}{${c}}`);
    } else if (line.startsWith("# ")) {
      closeItemize();
      closeJustify();
      closeCvgroup();
      out.push(`\\cvsection{${inline(line.slice(2))}}`);
    } else if (line.startsWith("- ")) {
      closeJustify();
      if (!inItemize) {
        out.push("\\begin{itemize}");
        inItemize = true;
      }
      out.push(`  \\item ${inline(line.slice(2))}`);
    } else if (line.startsWith("**")) {
      closeItemize();
      closeJustify();
      out.push(inline(line));
      lastPlain = true;
    } else {
      closeItemize();
      if (!inJustify) {
        out.push("\\begin{justify}");
        inJustify = true;
      }
      out.push(inline(line));
    }
  }
  closeItemize();
  closeJustify();
  closeCvgroup();

  return out.join("\n") + "\n";
}

const check = process.argv.includes("--check");
let stale = false;

for (const lang of LANGS) {
  const mdPath = `contents-${lang}.md`;
  const texPath = `contents-${lang}.tex`;
  const md = await Bun.file(mdPath).text();
  const header = `% Generated by scripts/md2tex.ts from ${mdPath} — do not edit.\n`;
  const tex = header + generate(md);
  if (check) {
    if ((await Bun.file(texPath).text()) !== tex) {
      console.error(`${texPath} is stale; run \`just tex\``);
      stale = true;
    }
  } else {
    await Bun.write(texPath, tex);
    console.log(`${mdPath} -> ${texPath}`);
  }
}

if (stale) process.exit(1);
